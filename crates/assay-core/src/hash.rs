//! Hand-written digest primitives.
//!
//! Assay needs SHA-256 (artefact identity), SHA-1 and MD5 (to *recognise* weak
//! cryptography in signatures — never to create it), and CRC-32 (PE checksum,
//! zip integrity). Pulling in the `sha2`/`md-5` crates would work, but these
//! algorithms are also a documented part of this project's test surface: the
//! unit tests below pin them against the NIST/RFC vectors, so a regression in
//! the digest layer can never be mistaken for a regression in a parser.

