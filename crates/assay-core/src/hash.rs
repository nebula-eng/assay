/// Compute the MD5 digest of `data`.
///
/// MD5 appears here for the same reason SHA-1 does: to detect legacy signature
/// and integrity schemes that should be treated as broken.
pub fn md5(data: &[u8]) -> [u8; 16] {
    let mut h: [u32; 4] = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476];

    let bit_len = (data.len() as u64).wrapping_mul(8);
    let padded_len = (data.len() + 9).div_ceil(64) * 64;
    let mut msg = Vec::with_capacity(padded_len);
    msg.extend_from_slice(data);
    msg.push(0x80);
    msg.resize(padded_len - 8, 0);
    // MD5 length is little-endian, unlike SHA-1/SHA-256.
    msg.extend_from_slice(&bit_len.to_le_bytes());

    for chunk in msg.chunks_exact(64) {
        let mut m = [0u32; 16];
        for (i, word) in chunk.chunks_exact(4).enumerate() {
            m[i] = u32::from_le_bytes([word[0], word[1], word[2], word[3]]);
        }

        let (mut a, mut b, mut c, mut d) = (h[0], h[1], h[2], h[3]);

        for i in 0..64 {
            let (f, g) = match i {
                0..=15 => ((b & c) | (!b & d), i),
                16..=31 => ((d & b) | (!d & c), (5 * i + 1) % 16),
                32..=47 => (b ^ c ^ d, (3 * i + 5) % 16),
                _ => (c ^ (b | !d), (7 * i) % 16),
            };
            let tmp = d;
            d = c;
            c = b;
            let sum = a.wrapping_add(f).wrapping_add(MD5_K[i]).wrapping_add(m[g]);
            b = b.wrapping_add(sum.rotate_left(MD5_S[i]));
            a = tmp;
        }

        h[0] = h[0].wrapping_add(a);
        h[1] = h[1].wrapping_add(b);
        h[2] = h[2].wrapping_add(c);
        h[3] = h[3].wrapping_add(d);
    }

    let mut out = [0u8; 16];
    for (i, word) in h.iter().enumerate() {
        out[i * 4..i * 4 + 4].copy_from_slice(&word.to_le_bytes());
    }
    out
}

/// CRC-32 (IEEE 802.3, reflected polynomial `0xEDB88320`).
pub fn crc32(data: &[u8]) -> u32 {
    static TABLE: std::sync::OnceLock<[u32; 256]> = std::sync::OnceLock::new();
    let table = TABLE.get_or_init(|| {
        let mut table = [0u32; 256];
        for (i, slot) in table.iter_mut().enumerate() {
            let mut c = i as u32;
            for _ in 0..8 {
                c = if c & 1 != 0 {
                    0xEDB8_8320 ^ (c >> 1)
                } else {
                    c >> 1
                };
            }
            *slot = c;
        }
        table
    });

    let mut crc = 0xFFFF_FFFFu32;
    for &byte in data {
        crc = table[((crc ^ u32::from(byte)) & 0xFF) as usize] ^ (crc >> 8);
    }
    crc ^ 0xFFFF_FFFF
}

/// Convenience wrapper: SHA-256 rendered as lowercase hex.
pub fn sha256_hex(data: &[u8]) -> String {
    crate::bytes::to_hex(&sha256(data))
}

/// Compute a short "imphash-style" digest over a list of imported symbols.
///
/// The classic import hash (used by PE malware clustering for two decades)
/// lowercases every `library.function` pair, joins them with commas, and takes
/// MD5. We keep the same construction so the resulting value is comparable with
/// ecosystem tooling, while documenting that it is a *similarity* signal, never
/// an identity.
pub fn import_hash<I, S>(imports: I) -> Option<String>
where
    I: IntoIterator<Item = (S, S)>,
    S: AsRef<str>,
{
    let mut parts: Vec<String> = imports
        .into_iter()
        .map(|(lib, func)| {
            let lib = lib.as_ref().to_ascii_lowercase();
            let func = func.as_ref().to_ascii_lowercase();
            let stem = lib
                .rsplit_once('.')
                .map(|(s, _)| s.to_string())
                .unwrap_or(lib);
            format!("{stem}.{func}")
        })
        .collect();
    if parts.is_empty() {
        return None;
    }
    parts.sort();
    Some(crate::bytes::to_hex(&md5(parts.join(",").as_bytes())))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(bytes: &[u8]) -> String {
        crate::bytes::to_hex(bytes)
    }

    #[test]
    fn sha256_matches_nist_vectors() {
        assert_eq!(
            hex(&sha256(b"")),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex(&sha256(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex(&sha256(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn sha256_handles_length_boundaries() {
        // 55, 56 and 64 bytes straddle the padding boundary.
        for n in [55usize, 56, 63, 64, 65, 119, 120] {
            let data = vec![0x61u8; n];
            let digest = sha256(&data);
            assert_eq!(digest.len(), 32);
            // Changing one byte must change the digest.
            let mut alt = data.clone();
            alt[n - 1] ^= 1;
            assert_ne!(digest, sha256(&alt));
        }
    }

    #[test]
    fn sha1_matches_rfc_vectors() {
        assert_eq!(hex(&sha1(b"")), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(
            hex(&sha1(b"abc")),
            "a9993e364706816aba3e25717850c26c9cd0d89d"
        );
        assert_eq!(
            hex(&sha1(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "84983e441c3bd26ebaae4aa1f95129e5e54670f1"
        );
    }

    #[test]
    fn md5_matches_rfc_vectors() {
        assert_eq!(hex(&md5(b"")), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(hex(&md5(b"abc")), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(
            hex(&md5(b"message digest")),
            "f96b697d7cb7938d525a2f31aaf161d0"
        );
    }

    #[test]
    fn crc32_matches_reference() {
        assert_eq!(crc32(b"123456789"), 0xCBF4_3926);
        assert_eq!(crc32(b""), 0);
    }

    #[test]
    fn import_hash_is_order_independent() {
        let a = import_hash([
            ("KERNEL32.dll", "CreateFileA"),
            ("user32.dll", "MessageBoxA"),
        ]);
        let b = import_hash([
            ("user32.dll", "MessageBoxA"),
            ("kernel32.dll", "CreateFileA"),
        ]);
        assert_eq!(a, b);
        assert!(a.is_some());
    }

    #[test]
    fn import_hash_empty_is_none() {
        let empty: [(&str, &str); 0] = [];
        assert!(import_hash(empty).is_none());
    }
}
